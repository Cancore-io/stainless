#!/usr/bin/env python3
"""Generate Pratt primality certificates for the curve constants (developer tool, untrusted).

The certificates are checked by the verified checker crypto.Pratt.certifies on the JVM
(run_jvm.sh), so nothing here is trusted: a wrong certificate is rejected there.
Needs sympy (factorisation). Writes ../PrattCerts.scala.
"""
import json
import sys
from pathlib import Path
from sympy import factorint, isprime

VECTORS = Path(__file__).resolve().parents[2] / "crypto-oracle" / "vectors" / "edge_cases_vectors.json"


def group_order(curve):
    """n from the oracle's order_mult_nG edge case ([n]G = O), so the order is not retyped here."""
    vs = json.loads(VECTORS.read_text())
    return int(next(v["k"] for v in vs if v["curve"] == curve and v["name"] == "order_mult_nG"), 16)


CONSTANTS = {
    "secp256k1P": 2**256 - 2**32 - 977,
    "secp256k1N": group_order("secp256k1"),
    "p256P": 2**256 - 2**224 + 2**192 + 2**96 - 1,
    "p256N": group_order("NIST_P256"),
}


def steps_for(p, done, out):
    """Append certificate steps for p (and, first, for the primes of p - 1) in dependency order."""
    if p == 2 or p in done:
        return
    assert isprime(p), p
    fs = factorint(p - 1)
    for q in sorted(fs):
        steps_for(q, done, out)
    a = next(a for a in range(2, p)
             if pow(a, p - 1, p) == 1 and all(pow(a, (p - 1) // q, p) != 1 for q in fs))
    out.append((p, a, [(q, e, (p - 1) // q) for q, e in sorted(fs.items())]))
    done.add(p)


def scala_list(items):
    return "List(" + ", ".join(items) + ")" if items else "List()"


def render():
    lines = [
        "package crypto",
        "",
        "import stainless.collection._",
        "",
        "// Generated by scripts/pratt_gen.py — do not edit. Checked by Pratt.certifies (run_jvm.sh).",
        "object PrattCerts {",
    ]
    for name, n in CONSTANTS.items():
        steps = []
        steps_for(n, set(), steps)
        rendered = []
        for p, a, fs in steps:
            factors = scala_list([f'PrattFactor(BigInt("{q}"), BigInt({e}), BigInt("{m}"))' for q, e, m in fs])
            rendered.append(f'PrattStep(BigInt("{p}"), BigInt({a}), {factors})')
        lines.append(f'  val {name}: BigInt = BigInt("{n}")')
        lines.append(f"  val {name}Cert: List[PrattStep] = List(")
        lines.append(",\n".join("    " + r for r in rendered))
        lines.append("  )")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    out = Path(__file__).resolve().parent.parent / "PrattCerts.scala"
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if out.read_text() == text else 1)
    out.write_text(text)
    print(f"wrote {out}")
