#!/usr/bin/env python3
"""Generate PrattTraces.scala: Stainless proofs that the curve certificates in PrattCerts.scala check.

Untrusted developer tool, standard library only. Every modPow in Pratt.stepOk gets a
square-and-multiply trace whose steps Stainless checks one ground `mod` at a time
(Pratt.traceBase / traceSq / traceSqMul); a wrong value is rejected there, not here.
Usage: pratt_trace_gen.py [--check]   (--check: exit 1 unless the file on disk is reproduced)
"""
import re
import sys
from pathlib import Path

SEGMENT = 16  # trace steps per lemma; 256 in one body overflows Stainless's TypeEncoding stack

HERE = Path(__file__).resolve().parent.parent
STEP = re.compile(r'  val (\w+)S(\d+): PrattStep = PrattStep\(BigInt\("(\d+)"\), BigInt\((\d+)\), List\((.*)\)\)$')
FACTOR = re.compile(r'PrattFactor\(BigInt\("(\d+)"\), BigInt\((\d+)\), BigInt\("(\d+)"\)\)')


def parse_certs(text):
    certs = {}
    for line in text.splitlines():
        m = STEP.match(line)
        if m:
            name, i, p, a, fs = m.groups()
            factors = [(int(q), int(e), int(c)) for q, e, c in FACTOR.findall(fs)]
            certs.setdefault(name, []).append((int(i), int(p), int(a), factors))
    for steps in certs.values():
        assert [s[0] for s in steps] == list(range(len(steps)))
    return certs


def lit(n):
    return f"BigInt({n})" if n < 2**31 else f'BigInt("{n}")'


def trace_lemmas(k, b, e, m):
    """Lemmas pw{k}s{j} (segments) and pw{k} proving modPow(b, e, m) == pow(b, e, m)."""
    out, segs, cur, h = [], [], 1, b % m
    steps = []
    for bit in bin(e)[3:]:
        n = 2 * cur + int(bit)
        h2 = (h * h % m) * (b % m) % m if bit == "1" else h * h % m
        steps.append(("traceSqMul" if bit == "1" else "traceSq", cur, h, h2, n))
        cur, h = n, h2
    bb, mm = lit(b), f"m{k}"
    out.append(f"  val {mm}: BigInt = {lit(m)}")
    for j in range(0, len(steps), SEGMENT):
        sg = steps[j:j + SEGMENT]
        name = f"pw{k}s{j // SEGMENT}"
        segs.append(name)
        out.append("  @ghost @opaque")
        out.append(f"  def {name}(): Unit = {{")
        out.append(f"    require(modPow({bb}, {lit(sg[0][1])}, {mm}) == {lit(sg[0][2])})")
        out.append(f"    val h0 = {lit(sg[0][2])}")
        out.append(f"    val e0 = {lit(sg[0][1])}")
        for i, (fn, _, _, h2, _) in enumerate(sg):
            out.append(f"    val h{i + 1} = {lit(h2)}")
            out.append(f"    {fn}({bb}, e{i}, {mm}, h{i}, h{i + 1})")
            if i + 1 < len(sg):
                out.append(f"    val e{i + 1} = 2 * e{i}" + (" + 1" if fn == "traceSqMul" else ""))
        out.append(f"  }}.ensuring(_ => modPow({bb}, {lit(sg[-1][4])}, {mm}) == {lit(sg[-1][3])})")
    out.append("  @ghost @opaque")
    out.append(f"  def pw{k}(): Unit = {{")
    out.append(f"    traceBase({bb}, {mm}, {lit(b % m)})")
    out += [f"    {s}()" for s in segs]
    out.append(f"  }}.ensuring(_ => modPow({bb}, {lit(e)}, {mm}) == {lit(pow(b, e, m))})")
    return out


def render(certs):
    lines = [
        "package crypto",
        "",
        "import stainless.lang._",
        "import stainless.annotation._",
        "import stainless.collection._",
        "import crypto.NumberTheory._",
        "import crypto.Pratt._",
        "",
        "// Generated by scripts/pratt_trace_gen.py from PrattCerts.scala — do not edit (verify.sh checks it is reproduced).",
        "object PrattTraces {",
    ]
    traces = {}

    def pw(b, e, m):
        if (b, e, m) not in traces:
            traces[(b, e, m)] = len(traces)
            lines.extend(trace_lemmas(traces[(b, e, m)], b, e, m))
        return f"pw{traces[(b, e, m)]}()"

    for name, steps in certs.items():
        known = [2]
        for i, p, a, factors in steps:
            calls = [pw(a, p - 1, p)] + [pw(a, c, p) for _, _, c in factors]
            lines.append("  @ghost @opaque")
            lines.append(f"  def {name}S{i}Ok(): Unit = {{")
            lines += [f"    {c}" for c in calls]
            known_lit = "List(" + ", ".join(lit(q) for q in known) + ")"
            lines.append(f"  }}.ensuring(_ => stepOk(PrattCerts.{name}S{i}, {known_lit}))")
            known = [p] + known
        n = len(steps)
        known = [2]
        knowns = []
        for i, p, _, _ in steps:
            knowns.append(list(known))
            known = [p] + known
        for i in reversed(range(n)):
            k = "List(" + ", ".join(lit(q) for q in knowns[i]) + ")"
            lines.append("  @ghost @opaque")
            lines.append(f"  def {name}T{i}Ok(): Unit = {{")
            lines.append(f"    {name}S{i}Ok()")
            if i + 1 < n:
                lines.append(f"    {name}T{i + 1}Ok()")
            lines.append(f"    checkStepsCons(PrattCerts.{name}S{i}, PrattCerts.{name}T{i + 1}, {k})")
            lines.append(f"  }}.ensuring(_ => checkSteps(PrattCerts.{name}T{i}, {k}) && "
                         f"PrattCerts.{name}T{i}.last.p == PrattCerts.{name})")
        lines.append("  @ghost @opaque")
        lines.append(f"  def {name}Checked(): Unit = {{")
        lines.append(f"    {name}T0Ok()")
        lines.append(f"  }}.ensuring(_ => certifies(PrattCerts.{name}Cert, PrattCerts.{name}))")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render(parse_certs((HERE / "PrattCerts.scala").read_text()))
    out = HERE / "PrattTraces.scala"
    if "--check" in sys.argv:
        sys.exit(0 if out.exists() and out.read_text() == text else 1)
    out.write_text(text)
    print(f"wrote {out}")
